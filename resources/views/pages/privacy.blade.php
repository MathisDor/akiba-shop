<x-page title="Politique de confidentialité" intro="Quelles données nous collectons, pourquoi, et ce que vous pouvez en faire.">
    <h2>Données collectées</h2>
    <ul>
        <li><strong>Compte</strong> : nom, adresse email, numéro de téléphone, ville, mot de passe (stocké chiffré).</li>
        <li><strong>Annonces</strong> : contenu, photos, pays et ville, numéro de contact.</li>
        <li><strong>Utilisation</strong> : favoris, signalements, nombre de vues des annonces.</li>
    </ul>

    <h2>Ce qui est public</h2>
    <p>Le contenu de vos annonces, votre nom affiché et le numéro de contact de l’annonce sont visibles par les visiteurs, afin qu’ils puissent vous joindre. Votre adresse email n’est jamais affichée.</p>

    <h2>Utilisation</h2>
    <p>Ces données servent uniquement à faire fonctionner le service : publication et modération des annonces, sécurité des comptes, lutte contre la fraude. Elles ne sont pas vendues.</p>

    <h2>Cookies</h2>
    <p>Nous utilisons des cookies techniques indispensables (session de connexion, sécurité des formulaires) et un cookie de préférence pour le mode « Économie de données ».</p>

    <h2>Vos droits</h2>
    <p>Vous pouvez modifier vos informations depuis <a href="{{ route('account.profile') }}">Mon compte</a> et supprimer vos annonces à tout moment. Pour supprimer votre compte, <a href="{{ route('pages.contact') }}">contactez-nous</a>.</p>
</x-page>
