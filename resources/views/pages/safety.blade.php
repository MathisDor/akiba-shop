<x-page title="Conseils de sécurité" intro="La grande majorité des échanges se passent bien. Quelques réflexes suffisent pour éviter les mauvaises surprises.">
    <h2>Pour les acheteurs</h2>
    <ul>
        <li>Rencontrez le vendeur dans un lieu public et fréquenté, de préférence en journée.</li>
        <li>Examinez et testez l’article avant de payer (téléphone, électroménager, véhicule…).</li>
        <li><strong>N’envoyez jamais d’argent par Airtel Money ou Moov Money avant d’avoir vu l’article</strong>, même pour un « acompte » ou des « frais de livraison ».</li>
        <li>Pour un logement, visitez-le et vérifiez l’identité du propriétaire ou de l’agence avant de verser une caution.</li>
        <li>Méfiez-vous des prix anormalement bas et des vendeurs pressés.</li>
    </ul>

    <h2>Pour les vendeurs</h2>
    <ul>
        <li>Ne remettez pas l’article avant d’avoir reçu le paiement complet.</li>
        <li>Vérifiez la réception d’un transfert Mobile Money sur votre propre compte, pas sur une capture d’écran.</li>
        <li>Ne communiquez jamais vos codes secrets ou codes de confirmation reçus par SMS.</li>
    </ul>

